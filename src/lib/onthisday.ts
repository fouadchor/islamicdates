export const otdPath = (slug: string) => `/on-this-day/${slug}/`;

export function fmtHDay(hm: number, hd: number): string {
  return `${hd} ${H_MON_AR[hm - 1]}`;
}

export function eventsOn(hm: number, hd: number): OtdEvent[] {
  return OTD_EVENTS.filter(e => e.hm === hm && e.hd === hd);
}

/**
 * الحدث المعروض ليوم هجري معيّن.
 * تطابق تام إن وُجد (مع تدوير سنوي إذا تعددت أحداث اليوم)،
 * وإلا أقرب حدث في الشهر نفسه مع exact=false ليُعرض توضيح «من أبرز أحداث الشهر».
 */
export function eventForDay(hm: number, hd: number, rot = 0): { ev: OtdEvent; exact: boolean } {
  const exact = eventsOn(hm, hd);
  if (exact.length) return { ev: exact[((rot % exact.length) + exact.length) % exact.length], exact: true };
  const month = OTD_EVENTS.filter(e => e.hm === hm);
  const pool = month.length ? month : OTD_EVENTS;
  let best = pool[0];
  for (const e of pool) if (Math.abs(e.hd - hd) < Math.abs(best.hd - hd)) best = e;
  return { ev: best, exact: false };
}

/** نص المشاركة عبر واتساب (يظهر رابط القصة كبطاقة معاينة في المحادثة). */
export function whatsappHref(ev: OtdEvent): string {
  const txt =
    `🌙 في مثل هذا اليوم الهجري (${fmtHDay(ev.hm, ev.hd)})\n` +
    `*${ev.title}* — ${ev.year}\n\n` +
    `${ev.summary}\n\n` +
    `اقرأ القصة كاملة:\nhttps://islamicdates.org${otdPath(ev.slug)}`;
  return 'https://wa.me/?text=' + encodeURIComponent(txt);
}

/** أحداث الشهر مرتبة بالأيام (لأرشيف الصفحة الرئيسية للقسم). */
export function eventsOfMonth(hm: number): OtdEvent[] {
  return OTD_EVENTS.filter(e => e.hm === hm).sort((a, b) => a.hd - b.hd);
}
